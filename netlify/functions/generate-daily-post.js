// netlify/functions/generate-daily-post.js
//
// Runs on a schedule (see `config.schedule` below) and is the real mechanism
// behind "daily-auto-posting blog." A static Astro site has no database and
// no runtime write access to its own deployed files, so the only correct
// way to auto-publish is: generate the day's post, commit it to the
// connected GitHub repository via the GitHub Contents API, and let
// Netlify's existing auto-deploy-on-push handle the rebuild. The new post
// appears through the exact same content-collection pipeline as every
// hand-written post in src/content/blog/ — there is no separate "auto
// posts" system to maintain.
//
// REQUIRED ENVIRONMENT VARIABLES (set in Netlify → Site configuration →
// Environment variables, never committed to the repo):
//   GITHUB_TOKEN   — fine-grained PAT scoped to Contents: Read & Write on
//                    this repository only.
//   GITHUB_REPO    — "owner/repo", e.g. "cloudgridafrica/cloudgridafrica-com"
//   GITHUB_BRANCH  — defaults to "main" if unset.
//
// This function deliberately does NOT call a third-party LLM API to write
// prose. It synthesizes a structured digest from curated source feeds using
// the same allowlisted-source pattern as netlify/functions/feed.js. If you
// want AI-assisted long-form drafting on top of this digest, that is a
// separate, explicitly-reviewed editorial step — not something that should
// publish unsupervised to a public compliance-focused engineering blog.

const SOURCES = [
  { key: "security", label: "Security", url: "https://feeds.feedburner.com/TheHackersNews" },
  { key: "cloud", label: "Cloud", url: "https://aws.amazon.com/blogs/aws/feed/" },
  { key: "africa", label: "Regional", url: "https://techcabal.com/feed/" },
];

const GITHUB_API = "https://api.github.com";

function todayISO() {
  return new Date().toISOString().slice(0, 10); // YYYY-MM-DD
}

function pluckTag(block, tag) {
  const match = block.match(new RegExp(`<${tag}\\b[^>]*>([\\s\\S]*?)<\\/${tag}>`, "i"));
  return match ? match[1].replace(/^\s*<!\[CDATA\[([\s\S]*?)\]\]>\s*$/i, "$1").trim() : null;
}

async function fetchHeadline(source) {
  try {
    const res = await fetch(source.url, {
      headers: { "User-Agent": "CloudGridAfrica-DailyBrief/1.0" },
    });
    if (!res.ok) return null;
    const xml = await res.text();
    const block = xml.match(/<item\b[\s\S]*?<\/item>/i)?.[0];
    if (!block) return null;
    const title = pluckTag(block, "title");
    if (!title) return null;
    return { label: source.label, title };
  } catch {
    return null;
  }
}

function buildMarkdown(date, headlines) {
  const frontmatter = [
    "---",
    `title: "Daily Brief — ${date}"`,
    `description: "Today's Kenya, Africa, and world tech signal relevant to cloud, security, and compliance engineering — curated and published automatically."`,
    `publishDate: ${date}`,
    `author: "CloudGrid Africa Engineering"`,
    `category: "industry"`,
    `tags: ["Daily Brief", "Kenya", "Africa", "World Tech"]`,
    `autoGenerated: true`,
    `draft: false`,
    "---",
  ].join("\n");

  const body = [
    "",
    "*This post was generated by CloudGrid Africa's daily publishing pipeline " +
      "(`netlify/functions/generate-daily-post.js`), which curates same-day coverage " +
      "across security, cloud, and East African tech sources into a short editorial digest. " +
      "Auto-generated posts are labeled as such and are not a substitute for the editorial " +
      "pieces published separately by our engineering team.",
    "",
    "## Today's signal",
    "",
    ...headlines.map((h) => `**${h.label}** — ${h.title}`),
    "",
    "---",
    "",
    "*Want this analysis applied to your own stack? [Schedule an engineering consultation](/#contact).*",
    "",
  ].join("\n");

  return frontmatter + "\n" + body;
}

async function fileExistsOnGitHub({ repo, branch, path, token }) {
  const res = await fetch(
    `${GITHUB_API}/repos/${repo}/contents/${encodeURIComponent(path)}?ref=${branch}`,
    { headers: { Authorization: `Bearer ${token}`, Accept: "application/vnd.github+json" } }
  );
  return res.status === 200;
}

async function commitToGitHub({ repo, branch, path, content, token, message }) {
  const res = await fetch(`${GITHUB_API}/repos/${repo}/contents/${encodeURIComponent(path)}`, {
    method: "PUT",
    headers: {
      Authorization: `Bearer ${token}`,
      Accept: "application/vnd.github+json",
      "Content-Type": "application/json",
    },
    body: JSON.stringify({
      message,
      content: Buffer.from(content, "utf-8").toString("base64"),
      branch,
    }),
  });

  if (!res.ok) {
    const detail = await res.text();
    throw new Error(`GitHub commit failed (${res.status}): ${detail}`);
  }

  return res.json();
}

export default async () => {
  const token = process.env.GITHUB_TOKEN;
  const repo = process.env.GITHUB_REPO;
  const branch = process.env.GITHUB_BRANCH || "main";

  if (!token || !repo) {
    console.error(
      "[generate-daily-post] Missing GITHUB_TOKEN or GITHUB_REPO env var — skipping run."
    );
    return new Response(
      JSON.stringify({ status: "skipped", reason: "missing_env" }),
      { status: 200, headers: { "Content-Type": "application/json" } }
    );
  }

  const date = todayISO();
  const path = `src/content/blog/daily-brief-${date}.md`;

  if (await fileExistsOnGitHub({ repo, branch, path, token })) {
    return new Response(
      JSON.stringify({ status: "skipped", reason: "already_published", path }),
      { status: 200, headers: { "Content-Type": "application/json" } }
    );
  }

  const results = await Promise.all(SOURCES.map(fetchHeadline));
  const headlines = results.filter(Boolean);

  if (headlines.length === 0) {
    console.warn("[generate-daily-post] No source feeds returned content — skipping publish.");
    return new Response(
      JSON.stringify({ status: "skipped", reason: "no_source_content" }),
      { status: 200, headers: { "Content-Type": "application/json" } }
    );
  }

  const markdown = buildMarkdown(date, headlines);

  try {
    await commitToGitHub({
      repo,
      branch,
      path,
      content: markdown,
      token,
      message: `chore(blog): auto-publish daily brief for ${date}`,
    });
    return new Response(JSON.stringify({ status: "published", path }), {
      status: 200,
      headers: { "Content-Type": "application/json" },
    });
  } catch (err) {
    console.error("[generate-daily-post] Publish failed:", err);
    return new Response(JSON.stringify({ status: "error", message: String(err) }), {
      status: 500,
      headers: { "Content-Type": "application/json" },
    });
  }
};

export const config = {
  // Runs once daily at 05:00 UTC (08:00 EAT) — early enough that a fresh
  // brief is live before the Nairobi business day starts.
  schedule: "0 5 * * *",
};
