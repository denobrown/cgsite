// api/generate-daily-post.js
//
// Vercel Edge Function, invoked by Vercel Cron (see the `crons` entry in
// vercel.json). Direct port of
// netlify/functions/generate-daily-post.js — same mechanism, same reasoning
// (a static site has no runtime write access to its own deployed files, so
// the only correct way to auto-publish is committing a new file to the
// connected GitHub repo and letting the platform's normal
// deploy-on-push handle the rebuild). Only two things changed for this
// platform:
//   1. Trigger mechanism: Vercel Cron instead of Netlify's
//      `export const config = { schedule: ... }`.
//   2. Base64 encoding uses the Web-standard `btoa()` instead of Node's
//      `Buffer`, so this runs on the Edge runtime — same runtime as
//      api/feed.js, avoiding any Node-vs-Edge signature differences between
//      the two functions.
//
// SECURITY — Vercel Cron requests:
// Set a CRON_SECRET environment variable. Vercel automatically attaches
// `Authorization: Bearer <CRON_SECRET>` to requests it makes to a
// configured cron path, and this handler verifies that header before doing
// anything — without it, this endpoint would be a public, unauthenticated
// URL that anyone could hit to force a commit against your repo.

export const config = {
  runtime: "edge",
};

const SOURCES = [
  { key: "security", label: "Security", url: "https://feeds.feedburner.com/TheHackersNews" },
  { key: "cloud", label: "Cloud", url: "https://aws.amazon.com/blogs/aws/feed/" },
  { key: "africa", label: "Regional", url: "https://techcabal.com/feed/" },
];

const GITHUB_API = "https://api.github.com";

function todayISO() {
  return new Date().toISOString().slice(0, 10);
}

function pluckTag(block, tag) {
  const match = block.match(new RegExp(`<${tag}\\b[^>]*>([\\s\\S]*?)<\\/${tag}>`, "i"));
  return match ? match[1].replace(/^\s*<!\[CDATA\[([\s\S]*?)\]\]>\s*$/i, "$1").trim() : null;
}

async function fetchHeadline(source) {
  try {
    const res = await fetch(source.url, { headers: { "User-Agent": "CloudGridAfrica-DailyBrief/1.0" } });
    if (!res.ok) return null;
    const xml = await res.text();
    const block = xml.match(/<item\b[\s\S]*?<\/item>/i)?.[0];
    if (!block) return null;
    const title = pluckTag(block, "title");
    if (!title) return null;
    return { label: source.label, title };
  } catch {
    return null;
  }
}

function buildMarkdown(date, headlines) {
  const frontmatter = [
    "---",
    `title: "Daily Brief — ${date}"`,
    `description: "Today's Kenya, Africa, and world tech signal relevant to cloud, security, and compliance engineering — curated and published automatically."`,
    `publishDate: ${date}`,
    `author: "CloudGrid Africa Engineering"`,
    `category: "industry"`,
    `tags: ["Daily Brief", "Kenya", "Africa", "World Tech"]`,
    `autoGenerated: true`,
    `draft: false`,
    "---",
  ].join("\n");

  const body = [
    "",
    "*This post was generated by CloudGrid Africa's daily publishing pipeline " +
      "(`api/generate-daily-post.js`), which curates same-day coverage across " +
      "security, cloud, and East African tech sources into a short editorial digest. " +
      "Auto-generated posts are labeled as such and are not a substitute for the " +
      "editorial pieces published separately by our engineering team.",
    "",
    "## Today's signal",
    "",
    ...headlines.map((h) => `**${h.label}** — ${h.title}`),
    "",
    "---",
    "",
    "*Want this analysis applied to your own stack? [Schedule an engineering consultation](/#contact).*",
    "",
  ].join("\n");

  return frontmatter + "\n" + body;
}

// UTF-8-safe base64 encode using the Web-standard btoa (Edge runtime has no
// Buffer). TextEncoder → byte string → btoa is the standard workaround for
// btoa's Latin1-only limitation.
function toBase64(str) {
  const bytes = new TextEncoder().encode(str);
  let binary = "";
  bytes.forEach((b) => (binary += String.fromCharCode(b)));
  return btoa(binary);
}

async function fileExistsOnGitHub({ repo, branch, path, token }) {
  const res = await fetch(
    `${GITHUB_API}/repos/${repo}/contents/${encodeURIComponent(path)}?ref=${branch}`,
    { headers: { Authorization: `Bearer ${token}`, Accept: "application/vnd.github+json" } }
  );
  return res.status === 200;
}

async function commitToGitHub({ repo, branch, path, content, token, message }) {
  const res = await fetch(`${GITHUB_API}/repos/${repo}/contents/${encodeURIComponent(path)}`, {
    method: "PUT",
    headers: {
      Authorization: `Bearer ${token}`,
      Accept: "application/vnd.github+json",
      "Content-Type": "application/json",
    },
    body: JSON.stringify({ message, content: toBase64(content), branch }),
  });

  if (!res.ok) {
    const detail = await res.text();
    throw new Error(`GitHub commit failed (${res.status}): ${detail}`);
  }
  return res.json();
}

export default async function handler(request) {
  const cronSecret = process.env.CRON_SECRET;
  if (cronSecret) {
    const authHeader = request.headers.get("authorization");
    if (authHeader !== `Bearer ${cronSecret}`) {
      return new Response(JSON.stringify({ error: "Unauthorized" }), {
        status: 401,
        headers: { "Content-Type": "application/json" },
      });
    }
  }

  const token = process.env.GITHUB_TOKEN;
  const repo = process.env.GITHUB_REPO;
  const branch = process.env.GITHUB_BRANCH || "main";

  if (!token || !repo) {
    console.error("[generate-daily-post] Missing GITHUB_TOKEN or GITHUB_REPO — skipping run.");
    return new Response(JSON.stringify({ status: "skipped", reason: "missing_env" }), {
      status: 200,
      headers: { "Content-Type": "application/json" },
    });
  }

  const date = todayISO();
  const path = `src/content/blog/daily-brief-${date}.md`;

  if (await fileExistsOnGitHub({ repo, branch, path, token })) {
    return new Response(JSON.stringify({ status: "skipped", reason: "already_published", path }), {
      status: 200,
      headers: { "Content-Type": "application/json" },
    });
  }

  const results = await Promise.all(SOURCES.map(fetchHeadline));
  const headlines = results.filter(Boolean);

  if (headlines.length === 0) {
    return new Response(JSON.stringify({ status: "skipped", reason: "no_source_content" }), {
      status: 200,
      headers: { "Content-Type": "application/json" },
    });
  }

  const markdown = buildMarkdown(date, headlines);

  try {
    await commitToGitHub({
      repo,
      branch,
      path,
      content: markdown,
      token,
      message: `chore(blog): auto-publish daily brief for ${date}`,
    });
    return new Response(JSON.stringify({ status: "published", path }), {
      status: 200,
      headers: { "Content-Type": "application/json" },
    });
  } catch (err) {
    console.error("[generate-daily-post] Publish failed:", err);
    return new Response(JSON.stringify({ status: "error", message: String(err) }), {
      status: 500,
      headers: { "Content-Type": "application/json" },
    });
  }
}
